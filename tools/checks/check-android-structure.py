#!/usr/bin/env python3
"""Enforce the Android source structure the plan promises.

Rules:
  * a Kotlin package matches its folder under ``src/*/kotlin``;
  * a test package also exists in production code: renaming or moving a package
    leaves its tests behind otherwise, where they still compile into a
    namespace nothing else owns;
  * a file carries one public top-level declaration, named after it - except a
    file of contracts: interfaces, enums, sealed and data classes may share one
    file, since they carry no behaviour. A plain ``class``, an ``object`` or top
    level functions never share;
  * no ``Utils``/``Helpers``/``Common``/``Manager`` file names;
  * everything under ``packages/`` (the client engine) imports no ``android.*``
    or ``androidx.*``;
  * everything under ``packages/`` stays out of ``com.hopa.capabilities.*``,
    which names the Android platform adapters only;
  * only ``CatalogRoutes`` picks a catalog platform target, so no client can
    read another platform's identifier by accident.

The check covers both the Android app and the shared packages, so a module that
moves between them keeps the same rules.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ANDROID = ROOT / "apps" / "android"
PACKAGES = ROOT / "packages"
BANNED = {"Utils", "Helpers", "Common", "Manager", "Misc"}
DECL = re.compile(
    r"^(?:public |internal |private |protected )?"
    r"(?:data |sealed |enum |abstract |open |annotation |fun )?"
    r"(class|interface|object|fun) ([A-Za-z_][A-Za-z0-9_]*)",
)
PACKAGE = re.compile(r"^package ([A-Za-z0-9_.]+)")
VISIBILITY = re.compile(r"^(?:private |internal |protected )")
PLATFORM_READ = re.compile(r"\b(?:app|target)\.(harmonyos|android|windows)\b")
PLATFORM_OWNER = "CatalogRoutes.kt"
MAX_CONTRACTS = 12
CONTRACT = re.compile(r"^(?:public |internal )?(?:data |sealed |enum )+(?:class|interface) ")
# Test-only packages with no production namesake: shared fakes and the fixtures
# the conformance tests read. Anything else under src/test belongs to a package
# production code ships.
TEST_SUPPORT = {
    "com.hopa.contracts.testing",
    "com.hopa.knowledge.testing",
    "com.hopa.execution.conformance",
}


def is_contract(line: str) -> bool:
    """A declaration that carries no behaviour: interface, enum, sealed or data class."""
    text = line.strip()
    if text.startswith("interface ") or " interface " in text:
        return True
    return bool(CONTRACT.match(text))


def kotlin_files() -> list[Path]:
    return sorted(
        list(ANDROID.glob("**/src/*/kotlin/**/*.kt"))
        + list(PACKAGES.glob("*/src/*/kotlin/**/*.kt"))
    )


def relative_package(path: Path) -> str | None:
    parts = path.parts
    if "kotlin" not in parts:
        return None
    index = parts.index("kotlin")
    folders = parts[index + 1 : -1]
    return ".".join(folders)


def production_packages() -> set[str]:
    """Every package some module ships, so a test cannot outlive its types."""
    packages: set[str] = set()
    for path in (
        list(ANDROID.glob("**/src/main/kotlin/**/*.kt"))
        + list(PACKAGES.glob("*/src/main/kotlin/**/*.kt"))
    ):
        package = relative_package(path)
        if package:
            packages.add(package)
    return packages


def source_set(path: Path) -> str | None:
    """The name under ``src/`` that holds this file: ``main``, ``test``, ..."""
    parts = path.parts
    if "kotlin" not in parts:
        return None
    index = parts.index("kotlin")
    return parts[index - 1] if index >= 1 else None


def is_test(path: Path) -> bool:
    name = source_set(path) or ""
    return name.startswith("test") or name.endswith("Test")


def check() -> list[str]:
    problems: list[str] = []
    production = production_packages()
    for path in kotlin_files():
        text = path.read_text(encoding="utf-8").lstrip("\ufeff")
        if path.stem in BANNED:
            problems.append(f"{path.relative_to(ROOT)}: banned file name")
        expected = relative_package(path)
        package = next(
            (PACKAGE.match(line).group(1) for line in text.splitlines() if PACKAGE.match(line)),
            "",
        )
        if expected and package != expected:
            problems.append(
                f"{path.relative_to(ROOT)}: package {package!r} does not match {expected!r}"
            )
        if is_test(path) and package and package not in production and package not in TEST_SUPPORT:
            problems.append(
                f"{path.relative_to(ROOT)}: test package {package!r} has no production "
                "code and is not a test-support package, so it outlived what it tests"
            )
        generated = text.startswith("// Generated by")
        declarations: list[tuple[str, str]] = []
        for line in text.splitlines():
            match = DECL.match(line)
            if not match:
                continue
            if VISIBILITY.match(line) and not line.startswith("internal "):
                continue
            declarations.append((match.group(1), match.group(2)))
        if not generated and declarations:
            if len(declarations) > 1:
                # Contracts may share a file; behaviour may not.
                behaviour = [
                    line.strip()
                    for line in text.splitlines()
                    if DECL.match(line) and not is_contract(line)
                ]
                if behaviour:
                    problems.append(
                        f"{path.relative_to(ROOT)}: {len(declarations)} public declarations, "
                        f"and {behaviour[0]!r} carries behaviour"
                    )
                elif len(declarations) > MAX_CONTRACTS:
                    problems.append(
                        f"{path.relative_to(ROOT)}: {len(declarations)} declarations in one "
                        f"file (limit {MAX_CONTRACTS})"
                    )
            else:
                kind, name = declarations[0]
                if path.stem != name:
                    problems.append(
                        f"{path.relative_to(ROOT)}: file name does not match {kind} {name}"
                    )
        relative = path.relative_to(ROOT)
        if path.name != PLATFORM_OWNER and relative.parts[0] in {"packages", "apps"}:
            for number, line in enumerate(text.splitlines(), 1):
                match = PLATFORM_READ.search(line)
                if match:
                    problems.append(
                        f"{relative}:{number}: reads a {match.group(1)} target outside "
                        f"{PLATFORM_OWNER}"
                    )
        if relative.parts[0] == "packages":
            for number, line in enumerate(text.splitlines(), 1):
                stripped = line.strip()
                if stripped.startswith("import android.") or stripped.startswith("import androidx."):
                    problems.append(
                        f"{relative}:{number}: a client package imports Android"
                    )
                # com.hopa.capabilities.* belongs to the platform adapters in
                # apps/android; the shared engine must not claim that name again.
                if "com.hopa.capabilities." in line:
                    problems.append(
                        f"{relative}:{number}: a client package uses the platform adapter "
                        "namespace com.hopa.capabilities"
                    )
    return problems


def main() -> int:
    problems = check()
    for problem in problems:
        print(f"FAIL  {problem}")
    print(f"{len(problems)} Android structure problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
